#!/usr/bin/env python3
"""Embeds Data/engines/*.json, Data/recipes/*.json and Data/anticheat/anticheat.json into Swift source.
Run after editing anything under Data/:  python3 Scripts/embed-data.py"""
import json, os, tempfile
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, "Sources/GamePortKit/Generated/BundledData.swift")
def load(kind):
    d = os.path.join(root, "Data", kind)
    items = []
    for name in sorted(os.listdir(d)):
        if name.endswith(".json"):
            with open(os.path.join(d, name), encoding="utf-8") as f:
                text = f.read()
            json.loads(text)  # fail loudly on bad JSON
            items.append(text)
    return items
def lit(s):
    # A raw multi-line string literal with enough # to never collide with the content.
    n = 1
    while ('"' + "#" * n) in s or ("\\" + "#" * n) in s: n += 1
    h = "#" * n
    return h + '"""\n' + s.rstrip("\n") + '\n"""' + h
# Publish only after every source has parsed and the complete Swift file is on disk.
with tempfile.TemporaryDirectory(dir=os.path.dirname(out)) as temp, \
        open(os.path.join(temp, "BundledData.swift"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by Scripts/embed-data.py from Data/. Do not edit.\n\n")
    f.write("enum BundledData {\n")
    for kind, name in (("engines", "engineManifests"), ("recipes", "recipes")):
        f.write(f"    static let {name}: [String] = [\n")
        for t in load(kind):
            f.write("        " + lit(t) + ",\n")
        f.write("    ]\n")
    with open(os.path.join(root, "Data", "anticheat", "anticheat.json"), encoding="utf-8") as ac:
        text = ac.read()
    json.loads(text)
    f.write("    static let antiCheat: String = " + lit(text) + "\n")
    with open(os.path.join(root, "Data/optional/kosmickrisp.json"), encoding="utf-8") as pins:
        text = pins.read()
        json.loads(text)
        f.write("    static let kosmicKrisp = " + lit(text) + "\n")
    with open(os.path.join(root, "Tools/kosmickrisp-shim/shim.c"), encoding="utf-8") as shim:
        f.write("    static let vulkanShimSource = " + lit(shim.read()) + "\n")
    with open(os.path.join(root, "Tools/fps-probe/fps_probe.m"), encoding="utf-8") as probe:
        f.write("    static let fpsProbeSource = " + lit(probe.read()) + "\n")
    f.write("}\n")
    f.flush()
    os.replace(f.name, out)
print("wrote", out)
